# =========================================================
# 2. GEOJSON
# =========================================================

features = []

for district in districts:

    ring = district["coords"] + [district["coords"][0]]

    feature = {
        "type": "Feature",

        "properties": {
            "name": district["name"],
            "sub": district["sub"],
            "pct": district["pct"],
            "color": district["color"],
        },

        "geometry": {
            "type": "Polygon",
            "coordinates": [ring]
        }
    }

    features.append(feature)

geojson_data = {
    "type": "FeatureCollection",
    "features": features
}

# =========================================================
# 3. CREATE MAP
# =========================================================

m = folium.Map(
    location=[41.360, 19.870],
    zoom_start=11,
    tiles="CartoDB positron",
)

# =========================================================
# 4. STYLING
# =========================================================

def style_function(feature):

    return {
        "fillColor": feature["properties"]["color"],
        "color": "white",
        "weight": 3,
        "fillOpacity": 0.75,
    }

def highlight_function(feature):

    return {
        "fillColor": feature["properties"]["color"],
        "color": "black",
        "weight": 4,
        "fillOpacity": 0.95,
    }

# =========================================================
# 5. ADD DISTRICTS
# =========================================================

folium.GeoJson(

    geojson_data,

    name="Tirana Districts",

    style_function=style_function,

    highlight_function=highlight_function,

    tooltip=GeoJsonTooltip(
        fields=["name", "sub", "pct"],
        aliases=["Lagja:", "Zona:", "Popullsia:"],
        sticky=True,
    ),

    popup=GeoJsonPopup(
        fields=["name", "sub", "pct"],
        aliases=["Lagja", "Zona", "Popullsia %"],
    ),

).add_to(m)

